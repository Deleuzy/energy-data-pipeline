"""Generate the SYNTHETIC example site CSV (an invented small office building).

The profile is made up: 18 kWh/h base load, plus 55 kWh/h on weekdays 06-16 UTC,
plus deterministic noise. It is not measured data from any real site.
"""

from pathlib import Path

import numpy as np
import pandas as pd

rng = np.random.default_rng(42)
hours = pd.date_range("2026-10-01T00:00", "2026-10-15T00:00", freq="h", inclusive="left")
working = (hours.day_of_week < 5) & (hours.hour >= 6) & (hours.hour < 17)
kwh = 18 + 55 * working + rng.normal(0, 3, len(hours))
out = Path(__file__).with_name("synthetic_site_hourly.csv")
with out.open("w") as f:
    f.write("# SYNTHETIC DATA: invented hourly electricity use of a fictional office, not a real site.\n")
    f.write("# Generated by examples/make_synthetic_site.py (seed 42).\n")
    pd.DataFrame({"timestamp_utc": hours.strftime("%Y-%m-%dT%H:%M:%SZ"), "kwh": kwh.round(2)}).to_csv(f, index=False)

monthly = Path(__file__).with_name("synthetic_site_monthly.csv")
monthly.write_text(
    "# SYNTHETIC DATA: invented monthly electricity use of a fictional office, not a real site.\n"
    "month,kwh\n2026-10,21500\n"
)
print(out, len(hours))
